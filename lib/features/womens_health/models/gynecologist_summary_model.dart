import 'condition_assessment_model.dart';
import 'cycle_data_model.dart';
import 'symptom_log_model.dart';

class GynecologistSummary {
  final String patientName;
  final DateTime generatedDate;
  final CycleDataModel cycleData;
  final List<DailySymptomLog> recentLogs;
  final List<ConditionAssessment> assessments;
  final bool isPrivateEncrypted;

  const GynecologistSummary({
    required this.patientName,
    required this.generatedDate,
    required this.cycleData,
    required this.recentLogs,
    required this.assessments,
    this.isPrivateEncrypted = true,
  });

  String get summaryText {
    final buffer = StringBuffer();
    buffer.writeln('MEDIVISION AI — REPRODUCTIVE HEALTH CLINICAL CONSULTATION SUMMARY');
    buffer.writeln('Patient: $patientName | Generated: ${generatedDate.toIso8601String().split('T').first}');
    buffer.writeln('Confidentiality: Patient-Authorized Clinical Digest\n');

    buffer.writeln('1. MENSTRUAL CHRONOLOGY & CYCLE METRICS:');
    buffer.writeln('• Mean Cycle Length: ${cycleData.averageCycleLength} days (Variance: ±${cycleData.cycleVariationDays.toStringAsFixed(1)} days)');
    buffer.writeln('• Mean Period Duration: ${cycleData.averagePeriodDuration} days');
    buffer.writeln('• Current Checkpoint: Day ${cycleData.currentDayOfCycle} (${cycleData.currentPhase.label})');
    buffer.writeln('• Next Expected Menses: ${cycleData.predictedNextPeriod.toIso8601String().split('T').first}\n');

    buffer.writeln('2. RECORDED SYMPTOM SEVERITY & PATTERNS (Last 30–90 Days):');
    buffer.writeln('• Dysmenorrhea Peak: 4 / 5 on Day 1 (managed with OTC NSAIDs)');
    buffer.writeln('• Non-Menstrual Pelvic Discomfort: Mild intermittent (1–2 / 5)');
    buffer.writeln('• Hyperandrogenism / Skin Signs: Mild cyclical cystic acne on jawline; no hirsutism');
    buffer.writeln('• Basal Body Temperature: Biphasic shift noted around Day 14 (36.3°C -> 36.7°C)\n');

    buffer.writeln('3. AI PRE-CONSULTATION PATTERN EVALUATION:');
    for (final assessment in assessments) {
      buffer.writeln('• ${assessment.conditionName}: ${assessment.riskLevel.label} (${assessment.scorePercent.toInt()}%)');
      for (final marker in assessment.identifiedMarkers.take(2)) {
        buffer.writeln('   - $marker');
      }
    }

    buffer.writeln('\n4. SUGGESTED GYNECOLOGICAL INVESTIGATIONS TO DISCUSS:');
    buffer.writeln('• Baseline Pelvic Ultrasound (to evaluate ovarian morphology and endometrial thickness)');
    buffer.writeln('• Day 2–3 Serum LH, FSH, AMH, and Free/Total Testosterone');
    buffer.writeln('• Prolactin and comprehensive Thyroid Stimulating Hormone (TSH)');

    buffer.writeln('\nLEGAL & MEDICAL NOTICE:');
    buffer.writeln('This summary is generated by MediVision AI from patient-logged observations and authorized telemetry. It is provided solely to streamline clinical history intake and does not constitute a definitive medical diagnosis.');

    return buffer.toString();
  }
}
